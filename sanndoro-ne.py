# -----------------------------
# 円を描く関数
# -----------------------------
def draw_circle(x, y, r, color_name):
    penup()
    goto(x, y - r)
    setheading(0)
    color(color_name)
    begin_fill()
    pendown()
    circle(r)
    end_fill()

# -----------------------------
# 多角形を塗る関数
# -----------------------------
def draw_polygon(points, color_name):
    penup()
    goto(points[0])
    color(color_name)
    begin_fill()
    pendown()

    for p in points[1:]:
        goto(p)

    goto(points[0])
    end_fill()

